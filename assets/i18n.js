/*!
 * Glycogo website translations.
 *
 * A language picker is mounted into the site nav on every page. Choosing a
 * language stores the choice, sets <html lang>, and swaps the English copy for
 * the matching catalog. Catalogs are keyed by the English text itself, so a
 * string with no translation simply stays in English instead of going blank.
 *
 * Catalog files live in /assets/i18n/<code>.js and register:
 *   window.GLYCOGO_I18N[code] = { common: {...}, home: {...}, ... }
 *
 * Page keys come from the first path segment: "/instructions" -> "instructions".
 */
(function () {
  "use strict";

  var LANGUAGES = [
    { code: "en", label: "English" },
    { code: "es", label: "Español" },
    { code: "fr", label: "Français" },
    { code: "it", label: "Italiano" },
    { code: "de", label: "Deutsch" },
    { code: "nl", label: "Nederlands" }
  ];

  var PAGE_ALIASES = {
    "": "home",
    "index.html": "home",
    "delete-account": "deleteAccount",
    "fuel-ratio-calculator": "fuelRatio",
    "fuel-ratio-calculator.html": "fuelRatio",
    "substrate-explorer": "substrate",
    "athlete_supplement_timer.html": "supplementTimer"
  };

  // Routes that exist as prerendered pages under /<lang>/. Generated by
  // tools/build-i18n-pages.cjs — keep the two lists in step.
  var ROUTES = [
    "/",
    "/fuel-ratio-calculator/",
    "/substrate-explorer/",
    "/athlete_supplement_timer.html",
    "/instructions/",
    "/beta/",
    "/privacy/",
    "/terms/",
    "/delete-account/"
  ];

  var ATTRS = ["placeholder", "alt", "title", "aria-label"];
  var SKIP_TAGS = {
    SCRIPT: 1,
    STYLE: 1,
    NOSCRIPT: 1,
    TEMPLATE: 1,
    CODE: 1,
    PRE: 1,
    TEXTAREA: 1,
    SVG: 1
  };

  var STORAGE_KEY = "glycogo:lang";
  var active = { code: "en", dict: Object.create(null) };
  var catalogs = Object.create(null);
  var observer = null;
  var pending = null;
  var dirtyQueue = [];

  /* ---------------------------------------------------------------- helpers */

  function normalise(value) {
    return String(value).replace(/\s+/g, " ").trim();
  }

  // "/de/fuel-ratio-calculator/" -> ["de", "fuel-ratio-calculator"]
  function pathParts() {
    return location.pathname.split("/").filter(Boolean);
  }

  // The language baked into the URL by the prerender step, if any.
  function pathLanguage() {
    var parts = pathParts();
    if (!parts.length) return null;
    var first = parts[0].toLowerCase();
    return first !== "en" && isKnownLanguage(first) ? first : null;
  }

  function pageKey() {
    var parts = pathParts();
    if (parts.length && pathLanguage()) parts = parts.slice(1);
    var first = parts[0] || "";
    if (!first) return "home";
    if (PAGE_ALIASES[first]) return PAGE_ALIASES[first];
    return first;
  }

  // Canonical route for the page being viewed, stripped of any language
  // prefix, so the picker can send visitors to the matching prerendered page.
  function currentRoute() {
    var parts = pathParts();
    if (parts.length && pathLanguage()) parts = parts.slice(1);
    var route = "/" + parts.join("/");
    if (route === "/index.html") route = "/";
    else if (/\/index\.html$/.test(route)) route = route.slice(0, -"index.html".length);
    else if (!/\.html$/.test(route) && route !== "/") route += "/";
    return ROUTES.indexOf(route) === -1 ? null : route;
  }

  function urlForLanguage(code) {
    var route = currentRoute();
    if (!route) return null;
    var url = (code === "en" ? "" : "/" + code) + route;
    if (url === location.pathname + location.hash) return null;
    if (url === location.pathname && !location.hash) return null;
    return url + location.hash;
  }

  function loadCatalog(code) {
    if (catalogs[code]) return Promise.resolve(catalogs[code]);
    return new Promise(function (resolve) {
      var existing = window.GLYCOGO_I18N && window.GLYCOGO_I18N[code];
      if (existing) {
        catalogs[code] = existing;
        resolve(existing);
        return;
      }
      var script = document.createElement("script");
      script.src = "/assets/i18n/" + code + ".js";
      script.async = true;
      script.onload = function () {
        catalogs[code] = (window.GLYCOGO_I18N && window.GLYCOGO_I18N[code]) || {};
        resolve(catalogs[code]);
      };
      script.onerror = function () {
        catalogs[code] = {};
        resolve(catalogs[code]);
      };
      document.head.appendChild(script);
    });
  }

  function buildDictionary(catalog) {
    var dict = Object.create(null);
    if (!catalog) return dict;
    ["common", pageKey()].forEach(function (block) {
      var entries = catalog[block];
      if (!entries) return;
      for (var key in entries) {
        if (Object.prototype.hasOwnProperty.call(entries, key)) {
          dict[normalise(key)] = entries[key];
        }
      }
    });
    return dict;
  }

  /* ------------------------------------------------------------ translation */

  function isSkipped(node) {
    var el = node.nodeType === 1 ? node : node.parentElement;
    while (el) {
      if (el.nodeType === 1) {
        if (SKIP_TAGS[el.tagName]) return true;
        if (el.hasAttribute && el.hasAttribute("data-i18n-skip")) return true;
        if (el.classList && el.classList.contains("lang-picker")) return true;
      }
      el = el.parentElement;
    }
    return false;
  }

  function translateTextNode(node) {
    if (isSkipped(node)) return;
    var raw = node.nodeValue;
    if (!raw || !/\S/.test(raw)) return;

    var collapsed = normalise(raw);
    if (!collapsed) return;

    if (node.__i18nSrc === undefined || node.__i18nWritten !== raw) {
      // First sight of this node, or something else rewrote it since we did.
      node.__i18nSrc = collapsed;
      node.__i18nLead = raw.match(/^\s*/)[0];
      node.__i18nTail = raw.match(/\s*$/)[0];
      node.__i18nTranslated = false;
    }

    var value = active.dict[node.__i18nSrc];
    if (value == null && !node.__i18nTranslated) {
      // Nothing to substitute and nothing of ours to undo: leave it alone.
      node.__i18nWritten = raw;
      return;
    }

    var next = node.__i18nLead + (value != null ? value : node.__i18nSrc) + node.__i18nTail;
    if (next !== raw) node.nodeValue = next;
    node.__i18nTranslated = value != null;
    node.__i18nWritten = node.nodeValue;
  }

  function translateAttributes(el) {
    if (!el.getAttribute || isSkipped(el)) return;
    var tag = el.tagName;
    var store = el.__i18nAttrs || (el.__i18nAttrs = Object.create(null));
    var names = ATTRS.slice();

    if (tag === "INPUT" && /^(submit|button|reset)$/i.test(el.type || "")) names.push("value");
    if (tag === "META") {
      var metaKind = (el.getAttribute("name") || el.getAttribute("property") || "").toLowerCase();
      if (/^(description|og:title|og:description)$/.test(metaKind)) names.push("content");
    }

    names.forEach(function (name) {
      if (!el.hasAttribute(name)) return;
      var raw = el.getAttribute(name);
      if (!raw || !/\S/.test(raw)) return;
      if (store[name] === undefined || store[name + ":written"] !== raw) {
        store[name] = normalise(raw);
      }
      var value = active.dict[store[name]];
      var next = value != null ? value : store[name];
      if (next !== raw) el.setAttribute(name, next);
      store[name + ":written"] = el.getAttribute(name);
    });
  }

  function translateTree(root) {
    if (!root) return;
    if (root.nodeType === 3) {
      translateTextNode(root);
      return;
    }
    if (root.nodeType !== 1 && root.nodeType !== 9) return;

    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, {
      acceptNode: function (node) {
        if (node.nodeType === 1) {
          return SKIP_TAGS[node.tagName] || node.classList.contains("lang-picker")
            ? NodeFilter.FILTER_REJECT
            : NodeFilter.FILTER_SKIP;
        }
        return NodeFilter.FILTER_ACCEPT;
      }
    });

    var node = walker.nextNode();
    while (node) {
      translateTextNode(node);
      node = walker.nextNode();
    }

    var elements = root.querySelectorAll ? root.querySelectorAll("*") : [];
    for (var i = 0; i < elements.length; i++) translateAttributes(elements[i]);
    if (root.nodeType === 1) translateAttributes(root);
  }

  function translateHead() {
    if (document.title) {
      var el = document.querySelector("title");
      if (el) {
        var src = el.__i18nSrc || normalise(el.textContent);
        el.__i18nSrc = src;
        var value = active.dict[src];
        var next = value != null ? value : src;
        if (el.textContent !== next) el.textContent = next;
      }
    }
  }

  function apply() {
    if (!document.body) return;
    translateHead();
    translateTree(document.body);
    document.documentElement.lang = active.code;
    document.documentElement.classList.toggle("i18n", active.code !== "en");
    var select = document.querySelector(".lang-select");
    if (select) select.value = active.code;
  }

  /* ----------------------------------------------------------------- picker */

  function injectStyles() {
    if (document.getElementById("glycogo-i18n-style")) return;
    var style = document.createElement("style");
    style.id = "glycogo-i18n-style";
    style.textContent = [
      ".lang-picker{display:inline-flex;align-items:center;gap:.35rem;flex:0 0 auto;margin-left:.75rem;position:relative}",
      "html.i18n .nav-links{gap:1.15rem}",
      "html.i18n .nav-links>a,html.i18n .nav-cta{white-space:nowrap}",
      "@media (max-width:1100px){.lang-picker svg{display:none}html.i18n .nav-links{gap:.65rem}html.i18n .lang-select{max-width:6.4rem;font-size:.7rem;padding-right:1.15rem}}",
      ".lang-picker svg{width:15px;height:15px;flex:0 0 auto;fill:none;stroke:currentColor;stroke-width:1.8;stroke-linecap:round;stroke-linejoin:round;opacity:.65}",
      ".lang-select{appearance:none;-webkit-appearance:none;background-color:rgba(127,127,127,.07);border:1px solid rgba(127,127,127,.45);border-radius:6px;color:inherit;font-family:inherit;font-size:.78rem;font-weight:600;letter-spacing:.01em;padding:.34rem 1.45rem .34rem .5rem;cursor:pointer;line-height:1.2;max-width:8.5rem;background-image:url(\"data:image/svg+xml;charset=utf-8,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 10 6'%3E%3Cpath d='M1 1l4 4 4-4' fill='none' stroke='%23888' stroke-width='1.6' stroke-linecap='round' stroke-linejoin='round'/%3E%3C/svg%3E\");background-repeat:no-repeat;background-position:right .42rem center;background-size:9px 6px}",
      ".lang-select:hover{border-color:rgba(128,128,128,.7)}",
      ".lang-select:focus-visible{outline:2px solid #2e7d32;outline-offset:2px}",
      ".lang-select option{color:#1a1a3e;background:#fff}",
      "@media (max-width:720px){.lang-picker{margin-left:.5rem}.lang-select{font-size:.72rem;padding:.28rem 1.3rem .28rem .42rem}}"
    ].join("");
    document.head.appendChild(style);
  }

  function mountPicker() {
    if (document.querySelector(".lang-picker")) return;
    var host =
      document.querySelector("nav .nav-inner") ||
      document.querySelector("nav") ||
      document.querySelector("header");
    if (!host) return;

    var wrap = document.createElement("div");
    wrap.className = "lang-picker";

    // Adopt the nav link colour so the control stays legible on dark and
    // light headers without a per-page stylesheet rule.
    var reference = host.querySelector(".nav-links > a") || host.querySelector("a");
    if (reference) {
      var colour = getComputedStyle(reference).color;
      if (colour) wrap.style.color = colour;
    }
    wrap.innerHTML =
      '<svg viewBox="0 0 24 24" aria-hidden="true">' +
      '<circle cx="12" cy="12" r="9"></circle>' +
      '<path d="M3.5 9h17M3.5 15h17M12 3c2.5 2.7 2.5 15.3 0 18M12 3c-2.5 2.7-2.5 15.3 0 18"></path>' +
      "</svg>" +
      '<select class="lang-select" aria-label="Language"></select>';

    var select = wrap.querySelector("select");
    LANGUAGES.forEach(function (lang) {
      var option = document.createElement("option");
      option.value = lang.code;
      option.textContent = lang.label;
      select.appendChild(option);
    });
    select.value = active.code;
    select.addEventListener("change", function () {
      // Prerendered pages live at /<lang>/..., so switching language is a
      // navigation: the URL, <html lang>, title and body copy all agree.
      var url = urlForLanguage(select.value);
      if (url) {
        // Remember the choice before leaving, so the landing page's first-visit
        // redirect cannot bounce the visitor back to an older preference.
        persist(select.value);
        location.href = url;
        return;
      }
      setLanguage(select.value);
    });

    host.appendChild(wrap);
  }

  /* ------------------------------------------------------------------ state */

  function setLanguage(code, options) {
    var opt = options || {};
    var known = LANGUAGES.some(function (lang) {
      return lang.code === code;
    });
    if (!known) code = "en";

    var previous = active.code;
    if (document.documentElement.hasAttribute("data-i18n-pending")) return;

    if (code === "en") {
      active = { code: "en", dict: Object.create(null) };
      apply();
      persist(code);
      finish(code, previous, opt);
      return;
    }

    document.documentElement.setAttribute("data-i18n-pending", "");
    loadCatalog(code).then(function (catalog) {
      active = { code: code, dict: buildDictionary(catalog) };
      document.documentElement.removeAttribute("data-i18n-pending");
      apply();
      persist(code);
      finish(code, previous, opt);
    });
  }

  function persist(code) {
    try {
      localStorage.setItem(STORAGE_KEY, code);
    } catch (error) {
      /* storage can be unavailable in private modes; language still applies */
    }
  }

  function finish(code, previous, opt) {
    if (code !== previous || opt.force) {
      document.dispatchEvent(
        new CustomEvent("glycogo:language", { detail: { code: code, previous: previous } })
      );
    }
  }

  function isKnownLanguage(code) {
    return LANGUAGES.some(function (lang) {
      return lang.code === code;
    });
  }

  function queryLanguage() {
    var fromQuery = new URLSearchParams(location.search).get("lang");
    return fromQuery ? fromQuery.slice(0, 2).toLowerCase() : null;
  }

  // The visitor's browser preference, matched on the primary subtag so
  // "de-AT", "es-419" and "nl-BE" all resolve to a catalog we ship. Unknown
  // languages fall back to English rather than to a half-translated page.
  function detectLanguage() {
    var preferred = navigator.languages && navigator.languages.length
      ? navigator.languages
      : navigator.language
        ? [navigator.language]
        : [];
    for (var i = 0; i < preferred.length; i++) {
      var primary = String(preferred[i] || "").toLowerCase().split(/[-_]/)[0];
      if (primary && isKnownLanguage(primary)) return primary;
    }
    return "en";
  }

  // Priority: ?lang=, then a choice the visitor made earlier, then the browser's
  // preferred language. A detected language is deliberately *not* stored, so a
  // visitor who later changes their browser language sees the site follow it.
  // Anything unrecognised in storage is dropped so detection applies again.
  function initialLanguage() {
    // A prerendered page already says which language it is; the URL wins so a
    // stale stored choice or a browser locale can never rewrite a /de/ page.
    var fromPath = pathLanguage();
    if (fromPath) return { code: fromPath, remember: false };

    var fromQuery = queryLanguage();
    if (fromQuery && isKnownLanguage(fromQuery)) return { code: fromQuery, remember: true };

    var stored = null;
    try {
      stored = localStorage.getItem(STORAGE_KEY);
    } catch (error) {
      stored = null;
    }
    if (stored && isKnownLanguage(stored)) return { code: stored, remember: false };
    if (stored) {
      try {
        localStorage.removeItem(STORAGE_KEY);
      } catch (error) {
        /* storage unavailable; detection still applies */
      }
    }

    return { code: detectLanguage(), remember: false };
  }

  /* -------------------------------------------------------------- observers */

  function observe() {
    if (!document.body || observer) return;
    observer = new MutationObserver(function (records) {
      if (document.documentElement.hasAttribute("data-i18n-pending")) return;
      for (var i = 0; i < records.length; i++) {
        var record = records[i];
        if (record.type === "characterData") {
          dirtyQueue.push(record.target);
        } else {
          for (var j = 0; j < record.addedNodes.length; j++) {
            dirtyQueue.push(record.addedNodes[j]);
          }
        }
      }
      if (!dirtyQueue.length || pending) return;
      pending = setTimeout(function () {
        pending = null;
        var queue = dirtyQueue;
        dirtyQueue = [];
        for (var k = 0; k < queue.length; k++) {
          var node = queue[k];
          if (!node.isConnected) continue;
          if (node.nodeType === 3) translateTextNode(node);
          else translateTree(node);
        }
      }, 40);
    });
    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true
    });
  }

  /* ------------------------------------------------------------------- boot */

  function boot() {
    injectStyles();
    var initial = initialLanguage();
    // Keep a prerendered URL and a first-visit detection in sync: if the page
    // is prefixed, its language is already correct; if the detection picks one
    // and this page has a translated copy, move to it so the choice survives
    // sharing and reloads.
    var detected = initial.code;
    if (!pathLanguage() && detected !== "en" && !initial.remember) {
      var target = urlForLanguage(detected);
      if (target) {
        location.replace(target);
        return;
      }
    }
    var code = initial.code;
    if (!isKnownLanguage(code)) code = "en";
    // Set before the catalog arrives so assistive tech and the URL contract
    // never disagree with the language about to be rendered.
    document.documentElement.lang = code;

    function remember() {
      if (initial.remember) persist(code);
    }

    if (code === "en") {
      active = { code: "en", dict: Object.create(null) };
      mountPicker();
      apply();
      observe();
      remember();
      return;
    }

    document.documentElement.setAttribute("data-i18n-pending", "");
    loadCatalog(code).then(function (catalog) {
      active = { code: code, dict: buildDictionary(catalog) };
      document.documentElement.removeAttribute("data-i18n-pending");
      mountPicker();
      apply();
      observe();
      remember();
    });
  }

  window.GlycogoI18n = {
    setLanguage: function (code) {
      setLanguage(code, { force: true });
    },
    getLanguage: function () {
      return active.code;
    },
    // Translate a string outside the DOM (e.g. text written into a downloaded
    // calendar file). Unknown strings come back unchanged, as in the page.
    translate: function (text) {
      var value = active.dict[normalise(text)];
      return value == null ? text : value;
    },
    languages: LANGUAGES
  };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", boot, { once: true });
  } else {
    boot();
  }
})();
